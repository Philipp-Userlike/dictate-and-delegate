'use strict';
// Insert on the Mac: puts text at the cursor of the app in front.
//
// The default way is a paste: the text goes on the pasteboard (marked transient, so clipboard
// managers skip it), ⌘V is pressed, and half a second later everything that was on the pasteboard
// before is put back, unless something else changed it meanwhile. That works in every app that
// takes ⌘V: native fields, browsers (bb's web app), Electron apps, terminals. Setting the text
// through the Accessibility API (Android's way) works only in native text fields; in browsers and
// Electron apps it often reports success without the app noticing, so it's the opt-in
// "direct" way, checked afterwards and followed by a paste when it didn't land.
// Without the Accessibility permission nothing can be typed into other apps: the text is copied
// and the panel says "Copied instead, paste with ⌘V", as Android does without its service.

const { clipboard, systemPreferences } = require('electron');
const nativeMac = require('./macos-native');
const { target, replaceRange, landed } = require('../core/insert-logic');
const { SerialQueue, sleep } = require('../core/util');

/** How long the app in front gets to read the pasteboard before it's put back. */
const RESTORE_MS = 600;
/** How long a held modifier (the hotkey's ⌥) is waited for before ⌘V. */
const MODIFIERS_MS = 1500;

const queue = new SerialQueue();

function accessibility(prompt = false) {
  if (process.platform !== 'darwin') return false;
  try {
    return systemPreferences.isTrustedAccessibilityClient(prompt);
  } catch {
    return false;
  }
}

function copy(text) {
  clipboard.writeText(text);
}

async function paste(mac, text, log) {
  for (const until = Date.now() + MODIFIERS_MS; mac.modifiersHeld() && Date.now() < until; ) await sleep(25);
  let saved = null;
  try {
    saved = mac.pasteboard.save();
  } catch (e) {
    log(`insert: couldn't read the pasteboard (${e.message}); it won't be put back`);
  }
  const count = mac.pasteboard.write([
    [
      { type: 'public.utf8-plain-text', data: Buffer.from(text, 'utf8') },
      { type: 'org.nspasteboard.TransientType', data: Buffer.alloc(0) },
      { type: 'org.nspasteboard.AutoGeneratedType', data: Buffer.alloc(0) },
    ],
  ]);
  mac.pressPaste();
  await sleep(RESTORE_MS);
  if (saved && mac.pasteboard.changeCount() === count) mac.pasteboard.write(saved);
  else if (saved) log('insert: the pasteboard changed meanwhile; left as it is');
}

/**
 * Inserts text at the cursor. method: 'paste' (default) or 'direct'. Resolves to
 * {how: 'inserted'|'pasted'|'copied', why} — 'copied' with why 'accessibility' (no permission) or
 * 'no-field' (nothing has the focus).
 */
function insert(text, { method = 'paste', log = () => {} } = {}) {
  return queue.run(async () => {
    const mac = nativeMac.load();
    if (!mac || !accessibility()) {
      copy(text);
      return { how: 'copied', why: mac ? 'accessibility' : 'unavailable' };
    }
    const focus = mac.focus();
    const kind = target(focus);
    if (kind === 'none') {
      copy(text);
      return { how: 'copied', why: 'no-field' };
    }
    if (method === 'direct' && kind === 'text') {
      const err = mac.setSelectedText(text);
      await sleep(80);
      const after = mac.focus();
      if (err === 0 && landed(focus.value, after.value, text)) return { how: 'inserted' };
      log(`insert: direct insert didn't land (AXError ${err}, role ${focus.role}); pasting`);
    }
    await paste(mac, text, log);
    return { how: 'pasted' };
  });
}

/**
 * Insert refined: replaces `old` with `text` where it was inserted, if it's still there unchanged
 * right before the cursor (or selected); else inserts at the cursor. Resolves like insert(), plus
 * replaced: true|false.
 */
async function replace(old, text, opts = {}) {
  const mac = nativeMac.load();
  if (mac && accessibility()) {
    const selected = await queue.run(async () => {
      const focus = mac.focus();
      const range = replaceRange(focus.value, focus.selection, old);
      if (!range) return false;
      if (mac.select(range) !== 0) return false;
      const now = mac.focus().selection;
      return !!now && now.location === range.location && now.length === range.length;
    });
    if (selected) return { ...(await insert(text, opts)), replaced: true };
  }
  return { ...(await insert(text, opts)), replaced: false };
}

module.exports = { insert, replace, copy, accessibility, RESTORE_MS };
