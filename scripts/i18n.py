#!/usr/bin/env python3
"""UI translations for Dictate & Delegate.

  scripts/i18n.py extract            # English strings_ui.xml from every tr("…") in the code
  scripts/i18n.py translate de fr …  # fill missing entries via OpenRouter (OPENROUTER_API_KEY),
                                     # and drop the ones the code no longer uses

Keys are CRC32 of the English text, the same as I18n.key() in the app.
"""
import json, os, re, sys, urllib.request, zlib
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "app/src/main/java/app/driftdictation")
RES = os.path.join(ROOT, "app/src/main/res")
LANGS = {"de": "German", "fr": "French", "es": "Spanish", "it": "Italian",
         "pt": "Portuguese", "nl": "Dutch", "pl": "Polish"}
LIT = r'"((?:[^"\\]|\\.)*)"'


def unescape(java):
    return json.loads('"' + java.replace("\\'", "'") + '"')


def texts():
    found = {}
    for name in sorted(os.listdir(SRC)):
        if not name.endswith(".java"):
            continue
        code = open(os.path.join(SRC, name), encoding="utf-8").read()
        # The first argument of tr(…): one or more literals joined with +.
        for m in re.finditer(r'\b(?:tr|reason)\(\s*(' + LIT + r'(?:\s*\+\s*' + LIT + r')*)', code):
            text = "".join(unescape(x) for x in re.findall(LIT, m.group(1)))
            found[text] = name
        # Labels stored in English and translated when shown: tr(variable).
        for listing in ("TOPICS",):
            block = re.search(listing + r'\s*=\s*\{(.*?)\};', code, re.S)
            if block:
                for lit in re.findall(LIT, block.group(1)):
                    found[unescape(lit)] = name
    return found


# CLDR plural categories each language needs (android.icu PluralRules for integers).
CATEGORIES = {"en": ["one", "other"], "de": ["one", "other"], "nl": ["one", "other"],
              "fr": ["one", "many", "other"], "es": ["one", "many", "other"],
              "it": ["one", "many", "other"], "pt": ["one", "many", "other"],
              "pl": ["one", "few", "many", "other"]}


def plurals():
    """plural(n, "one", "other") calls: English forms by the key of the "other" text."""
    found = {}
    for name in sorted(os.listdir(SRC)):
        if name.endswith(".java"):
            code = open(os.path.join(SRC, name), encoding="utf-8").read()
            for one, other in re.findall(r'\bplural\([^,]+,\s*' + LIT + r'\s*,\s*' + LIT + r'\s*\)', code):
                found[key(unescape(other))] = {"one": unescape(one), "other": unescape(other)}
    return found


def key(text):
    return "t_%08x" % (zlib.crc32(text.encode("utf-8")) & 0xFFFFFFFF)


def xml_value(text):
    v = escape(text).replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    return "\\" + v if v[:1] in "@?" else v


def write(lang_dir, entries):
    os.makedirs(os.path.join(RES, lang_dir), exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by scripts/i18n.py. Keys are CRC32 of the English text. -->',
             '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,UnusedResources">']
    for k in sorted(entries):
        lines.append('    <string name="%s" formatted="false">%s</string>' % (k, xml_value(entries[k])))
    lines.append("</resources>\n")
    open(os.path.join(RES, lang_dir, "strings_ui.xml"), "w", encoding="utf-8").write("\n".join(lines))


def read(lang_dir):
    path = os.path.join(RES, lang_dir, "strings_ui.xml")
    if not os.path.exists(path):
        return {}
    out = {}
    for k, v in re.findall(r'<string name="(t_[0-9a-f]{8}(?:_[a-z]+)?)"[^>]*>(.*?)</string>', open(path, encoding="utf-8").read(), re.S):
        v = v.replace("\\n", "\n").replace("\\'", "'").replace('\\"', '"').replace("\\\\", "\\")
        v = v[1:] if v[:2] in ("\\@", "\\?") else v
        out[k] = v.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")
    return out


def placeholders(text):
    return sorted(re.findall(r"%(?:\d+\$)?[sdf]|%%", text))


def chat(prompt, data):
    body = {"model": "google/gemini-3.8-flash", "reasoning": {"effort": "low"},
            "response_format": {"type": "json_object"},
            "messages": [{"role": "system", "content": prompt},
                         {"role": "user", "content": json.dumps(data, ensure_ascii=False)}]}
    req = urllib.request.Request("https://openrouter.ai/api/v1/chat/completions",
                                 data=json.dumps(body).encode(),
                                 headers={"Authorization": "Bearer " + os.environ["OPENROUTER_API_KEY"],
                                          "Content-Type": "application/json"})
    reply = json.load(urllib.request.urlopen(req, timeout=600))["choices"][0]["message"]["content"]
    return json.JSONDecoder().raw_decode(reply[reply.find("{"):])[0]


def translate(lang, english):
    current = read("values-" + lang)
    todo = {k: v for k, v in english.items() if k not in current}
    if todo:
        prompt = (
            "Translate the UI strings of Dictate & Delegate, an Android dictation app, into %s. "
            "Return a JSON object with the same keys. Keep placeholders like %%1$s, %%2$d and %%%% exactly. "
            "Keep the names Dictate & Delegate, OpenRouter and model names unchanged. Keep symbols like ·, →, … and line breaks. "
            "Use the informal form of address (German: du). Short, natural app wording; button labels stay short."
        ) % LANGS[lang]
        result = chat(prompt, todo)
        for k, v in result.items():
            if k in todo and isinstance(v, str) and placeholders(v) == placeholders(todo[k]):
                current[k] = v
            elif k in todo:
                print("  rejected", lang, k, repr(v))
    forms = plurals()
    todo = {k: f for k, f in forms.items() if any("%s_%s" % (k, c) not in current for c in CATEGORIES[lang])}
    if todo:
        prompt = (
            "Translate these count phrases of Dictate & Delegate, an Android dictation app, into %s. "
            "Input: JSON of id -> English singular and plural. Return JSON id -> object with exactly "
            "the CLDR plural categories %s, each the full phrase for that category. Keep %%1$d exactly."
        ) % (LANGS[lang], ", ".join(CATEGORIES[lang]))
        result = chat(prompt, todo)
        for k, v in result.items():
            if k not in todo or not isinstance(v, dict):
                continue
            for c in CATEGORIES[lang]:
                if isinstance(v.get(c), str) and placeholders(v[c]) == ["%1$d"]:
                    current["%s_%s" % (k, c)] = v[c]
                else:
                    print("  rejected plural", lang, k, c, repr(v.get(c)))
    wanted = set(english) | {"%s_%s" % (k, c) for k in forms for c in CATEGORIES[lang]}
    write("values-" + lang, {k: v for k, v in current.items() if k in wanted})
    missing = [k for k in english if k not in current]
    print(lang, "translated", len(english) - len(missing), "missing", len(missing))


if __name__ == "__main__":
    english = {key(t): t for t in texts()}
    if sys.argv[1] == "extract":
        # Every category any language uses must exist in the default locale; English uses "other".
        forms = {"%s_%s" % (k, c): f["one" if c == "one" else "other"]
                 for k, f in plurals().items() for c in ("one", "few", "many", "other")}
        write("values", {**english, **forms})
        print("strings", len(english))
    elif sys.argv[1] == "translate":
        for lang in sys.argv[2:] or LANGS:
            translate(lang, english)
